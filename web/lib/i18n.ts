export function getOcrLangs(lang: Lang): string {
  switch (lang) {
    case 'en':
      return 'eng';
    case 'te':
      return 'eng+tel';
    case 'hi':
      return 'eng+hin';
    case 'all':
    default:
      return 'eng+tel+hin';
  }
}

export function getUiLang(lang: Lang): 'en' | 'te' | 'hi' {
  if (lang === 'all') return 'en';
  return lang;
}

